#!/usr/bin/env python3
"""Generate jni_gen.h: the JNINativeInterface slot list (name, return type) from the JDK's jni.h.
Every slot gets a logging default stub; jni_fake.c overrides the ones that matter."""
import re, sys
src = open('/usr/lib/jvm/java-21-openjdk-amd64/include/jni.h').read()
body = src[src.index('struct JNINativeInterface_ {'):]
body = body[:body.index('\n};')]
slots = []
for m in re.finditer(r'(void \*reserved\d)|\n\s*([\w\s\*]+?)\s*\(JNICALL \*(\w+)\)', body):
    if m.group(1): slots.append(('void*', m.group(1)))
    else: slots.append((' '.join(m.group(2).split()), m.group(3)))
assert len(slots) == 235, len(slots)
with open('jni_gen.h', 'w') as f:
    f.write('/* generated by gen_jni.py from jni.h: %d slots */\n' % len(slots))
    f.write('static const char *jni_slot_names[%d] = {\n' % len(slots))
    for t, n in slots: f.write('  "%s",\n' % n)
    f.write('};\nstatic const char jni_slot_ret[%d] = {\n' % len(slots))
    for t, n in slots:
        k = 'v' if t == 'void' else ('f' if t == 'jfloat' else 'd' if t == 'jdouble' else 'i')
        f.write("  '%s', /* %s %s */\n" % (k, t, n))
    f.write('};\n')
print(len(slots), 'slots')
